#!/usr/bin/env python3
"""Build a deterministic, code-only worker payload embedded in BB's host artifact."""
import argparse,base64,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
FILES=['config.json','requirements.txt','requirements-cpu-py312.lock','models-manifest.json',
       'diarize.py','diarize_ms.py','transcribe.py','gigaam_gguf.py','probe_service.py',
       'run_service.py','lease_guard.py','model_cache.py','download_modelscope.py',
       'diarization_cache.py','export_speaker_samples.py','worker_progress.py','scripts/setup_worker.py']
def generate():
    version=json.loads((ROOT/'bb-plugin/package.json').read_text())['version']
    files={name:base64.b64encode((ROOT/name).read_bytes()).decode() for name in FILES}
    digest=hashlib.sha256(json.dumps(files,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    deps=hashlib.sha256(b''.join((ROOT/name).read_bytes() for name in ['requirements.txt','requirements-cpu-py312.lock'])).hexdigest()
    value={'version':version,'sha256':digest,'requirementsHash':deps,'files':files}
    return '// Generated by scripts/sync_runtime.py; code/config only, no models or user data.\nexport const runtimeBundle = '+json.dumps(value,separators=(',',':'))+';\n'
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    target=ROOT/'bb-plugin/runtime.generated.ts';value=generate()
    if args.check:
        if not target.exists() or target.read_text()!=value:raise SystemExit('Worker payload is stale; run scripts/sync_runtime.py')
    else:target.write_text(value)
    print('Worker payload OK')
if __name__=='__main__':main()
